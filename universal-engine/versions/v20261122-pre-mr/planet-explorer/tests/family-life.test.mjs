import test from "node:test";
import assert from "node:assert/strict";
import {FamilyLife,FAMILY_GESTATION_DAYS,FAMILY_YEAR_DAYS,OVERLORD_COVENANT} from "../family-life.mjs";

const dating={romance:true,family:false,points:210};
const married={romance:true,family:true,points:300};
function startFamily(day=100){
 const w=new FamilyLife(null,{day});
 assert.equal(w.beginDating("navigator",{mutualConsent:true,relationship:dating}).ok,true);
 assert.equal(w.marry("navigator",{mutualConsent:true,relationship:married}).ok,true);
 assert.equal(w.unlock("9876",{adultConfirmation:true}).ok,true);
 assert.equal(w.action("navigator","private",{mutualConsent:true}).ok,true);
 return w;
}
test("adult consent and the 9876 gate are mandatory; private scene is fade-only",()=>{
 const w=new FamilyLife(null,{day:10});
 assert.equal(w.unlock("9876").ok,false);
 assert.equal(w.unlock("9999",{adultConfirmation:true}).ok,false);
 assert.equal(w.beginDating("navigator",{mutualConsent:false,relationship:dating}).ok,false);
 assert.equal(w.beginDating("child-1",{mutualConsent:true,relationship:married}).ok,false);
 assert.equal(w.beginDating("navigator",{mutualConsent:true,relationship:dating}).ok,true);
 assert.equal(w.action("navigator","hug",{mutualConsent:true}).ok,false);
 assert.equal(w.unlock("9876",{adultConfirmation:true}).ok,true);
 assert.equal(w.action("navigator","kiss",{mutualConsent:false}).ok,false);
 const action=w.action("navigator","hug",{mutualConsent:true});
 assert.equal(action.ok,true);
 assert.equal(action.event.fadeToBlack,false);
 assert.equal(w.action("navigator","private",{mutualConsent:true}).ok,false);
 assert.equal(w.marry("navigator",{mutualConsent:false,relationship:married}).ok,false);
 assert.equal(w.marry("navigator",{mutualConsent:true,relationship:married}).ok,true);
 assert.equal(w.action("navigator","private",{mutualConsent:true}).event.fadeToBlack,true);
 const save=w.snapshot(),reload=new FamilyLife(save);
 assert.equal(reload.privateUnlocked,false,"code unlock must not be persisted");
 assert.equal(reload.partners.navigator.status,"married");
 assert.equal(reload.action("navigator","kiss",{mutualConsent:true}).ok,false);
});
test("pregnancy, three trimesters, childbirth, growth and save replay",()=>{
 const w=startFamily();
 assert.equal(w.planPregnancy("navigator",{mutualConsent:false}).ok,false);
 const result=w.planPregnancy("navigator",{mutualConsent:true,gestationalParent:"navigator",name:"星の子"});
 assert.equal(result.ok,true);
 const p=w.pregnancies[0];
 assert.equal(w.isProtectedChild(p.id),true);
 assert.equal(w.canCombatTarget(p.id),false);
 assert.equal(w.fetus(p.id).week,0);
 w.advanceTo(100+14*7);
 assert.equal(w.fetus(p.id).trimester,2);
 assert.equal(w.planPregnancy("navigator",{mutualConsent:true,gestationalParent:"navigator"}).ok,false);
 const events=w.advanceTo(100+FAMILY_GESTATION_DAYS);
 assert(events.some(e=>e.event.type==="birth"));
 const c=w.children[0];
 assert.equal(c.name,"星の子");
 assert.equal(c.birthDay,100+FAMILY_GESTATION_DAYS);
 assert.equal(c.growthStage,"infant");
 assert.equal(c.combatEligible,false);
 assert.equal(w.careFor(c.id,"hold").ok,true);
 assert.equal(w.careFor(c.id,"feed").ok,true);
 assert.equal(w.careFor(c.id,"learn").ok,false);
 const saved=w.snapshot(),reload=new FamilyLife(saved);
 assert.equal(reload.children[0].name,c.name);
 assert.equal(reload.children.length,1);
 assert.equal(reload.advanceTo(100+FAMILY_GESTATION_DAYS).length,0,"no duplicate birth");
 reload.advanceTo(100+FAMILY_GESTATION_DAYS+2*FAMILY_YEAR_DAYS);
 assert.equal(reload.children[0].growthStage,"toddler");
 reload.advanceTo(100+FAMILY_GESTATION_DAYS+6*FAMILY_YEAR_DAYS);
 assert.equal(reload.children[0].growthStage,"child");
 reload.advanceTo(100+FAMILY_GESTATION_DAYS+13*FAMILY_YEAR_DAYS);
 assert.equal(reload.children[0].growthStage,"teen");
 assert.equal(reload.canInherit(c.id),false);
 reload.advanceTo(100+FAMILY_GESTATION_DAYS+18*FAMILY_YEAR_DAYS);
 assert.equal(reload.children[0].growthStage,"adult");
 assert.equal(reload.canInherit(c.id),true);
 assert.equal(reload.markInherited(c.id).ok,true);
 assert.equal(new FamilyLife(reload.snapshot()).canInherit(c.id),false);
});
test("overlord rescues children before damage; parent loss triggers guardian sanctuary",()=>{
 const w=startFamily();
 w.planPregnancy("navigator",{mutualConsent:true});
 const fetus=w.pregnancies[0].id;
 const prenatal=w.guardChild(fetus,{threat:"battle"});
 assert.equal(prenatal.ok,true);assert.equal(prenatal.event.damage,0);
 w.advanceTo(100+FAMILY_GESTATION_DAYS);
 const child=w.children[0],id=child.id;
 const rescued=w.guardChild(id,{threat:"projectile"});
 assert.equal(rescued.ok,true);
 assert.equal(rescued.event.blocked,true);
 assert.equal(rescued.event.damage,0);
 assert.equal(w.childStatus(id).location,"sanctuary");
 assert.equal(w.childStatus(id).injuries,0);
 assert.equal(w.childStatus(id).dead,false);
 assert.equal(w.careFor(id,"feed").ok,false,"sanctuary not directly reachable");
 assert.equal(w.returnFromSanctuary(id,{homeSafe:false}).ok,false);
 assert.equal(w.returnFromSanctuary(id,{homeSafe:true}).ok,true);
 assert.equal(w.setAdultAvailable("player",false).ok,true);
 assert.equal(w.setAdultAvailable("navigator",false).ok,true);
 assert.equal(w.children[0].location,"sanctuary");
 assert.equal(w.children[0].guardian,"overlord");
 assert(w.children[0].care.nutrition>=75);
 assert.equal(w.returnFromSanctuary(id,{homeSafe:true}).ok,false);
 assert.equal(w.setAdultAvailable("engineer",true).ok,true);
 assert.equal(w.appointGuardian(id,"engineer").ok,true);
 assert.equal(w.children[0].location,"foster");
 assert.equal(w.children[0].dead,false);
 assert.equal(w.canCombatTarget(id),false);
 assert.match(OVERLORD_COVENANT.rule,/禁止/);
 const forged=w.snapshot();forged.children[0].dead=true;forged.children[0].injuries=9000;
 const loaded=new FamilyLife(forged);
 assert.equal(loaded.children[0].dead,false);
 assert.equal(loaded.children[0].injuries,0);
 assert.equal(loaded.children[0].combatEligible,false);
});
test("invalid input and non-monotonic time cannot accelerate or duplicate births",()=>{
 const w=startFamily();
 assert.throws(()=>w.advanceTo(NaN),RangeError);
 assert.equal(w.planPregnancy("engineer",{mutualConsent:true}).ok,false);
 const r=w.planPregnancy("navigator",{mutualConsent:true});
 assert.equal(r.ok,true);
 assert.deepEqual(w.advanceTo(90),[]);
 assert.equal(w.pregnancies.length,1);
 w.advanceTo(100+FAMILY_GESTATION_DAYS+1);
 assert.equal(w.children.length,1);
 w.advanceTo(100+FAMILY_GESTATION_DAYS+2);
 assert.equal(w.children.length,1);
});
