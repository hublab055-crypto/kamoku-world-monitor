export const BOOK_MAP=new Map(BOOKS.map(book=>[book.id,book]));
export const STARTING_SHELF=Object.freeze(BOOKS.map(book=>book.id));
export const BOOK_PAGE_CHARS=285;
export function pagesForBook(book,limit=BOOK_PAGE_CHARS){
 if(!book||!Array.isArray(book.chapters))throw new TypeError("Unknown book");
 if(!Number.isSafeInteger(limit)||limit<40||limit>2000)throw new RangeError("Invalid page length");
 const pages=[];
 for(const chapter of book.chapters){
  const paragraphs=chapter.paragraphs.map(p=>p.trim()).filter(Boolean);
  let contents=[],used=0;
  const flush=()=>{if(contents.length){pages.push({chapter:chapter.title,text:contents.join("\n\n")});contents=[];used=0;}};
  for(const paragraph of paragraphs){
   const letters=Array.from(paragraph);
   if(contents.length&&used+2+letters.length>limit)flush();
   for(let start=0;start<letters.length;){
    const capacity=limit-used-(contents.length?2:0);
    if(capacity<=0){flush();continue;}
    const chunk=letters.slice(start,start+capacity).join("");
    contents.push(chunk);used+=Array.from(chunk).length;start+=Array.from(chunk).length;
    if(start<letters.length)flush();
   }
  }
  flush();
 }
 return pages;
}
export class BookCollection{
 constructor(saved=null){
  const data=saved&&typeof saved==="object"?saved:{};
  this.carried=Array.isArray(data.carried)?[...new Set(data.carried.filter(id=>BOOK_MAP.has(id)))]:[];
  this.bookmarks={};
  for(const book of BOOKS){
   const page=Number(data.bookmarks?.[book.id]);
   if(Number.isSafeInteger(page)&&page>=0)this.bookmarks[book.id]=Math.min(page,pagesForBook(book).length-1);
  }
  this.fontSize=Number.isFinite(data.fontSize)?Math.max(15,Math.min(26,data.fontSize)):19;
 }
 ensureShelf(hut){
  if(!hut||hut.progress<1)return [];
  if(!Array.isArray(hut.bookshelfBooks))hut.bookshelfBooks=[...STARTING_SHELF];
  hut.bookshelfBooks=[...new Set(hut.bookshelfBooks.filter(id=>BOOK_MAP.has(id)))];
  return hut.bookshelfBooks;
 }
 available(hut=null){return [...new Set([...this.carried,...(hut?this.ensureShelf(hut):[])])].map(id=>BOOK_MAP.get(id));}
 has(id,hut=null){return this.carried.includes(id)||Boolean(hut&&this.ensureShelf(hut).includes(id));}
 take(id,hut){
  if(!BOOK_MAP.has(id)||!hut||this.carried.includes(id))return false;
  const shelf=this.ensureShelf(hut),i=shelf.indexOf(id);if(i<0)return false;
  shelf.splice(i,1);this.carried.push(id);return true;
 }
 putBack(id,hut){
  if(!hut||!BOOK_MAP.has(id))return false;
  const i=this.carried.indexOf(id);if(i<0)return false;
  const shelf=this.ensureShelf(hut);if(shelf.includes(id))return false;
  this.carried.splice(i,1);shelf.push(id);return true;
 }
 page(id){return this.bookmarks[id]||0;}
 bookmark(id,page){
  const book=BOOK_MAP.get(id);if(!book)return false;
  if(!Number.isSafeInteger(page)||page<0||page>=pagesForBook(book).length)return false;
  this.bookmarks[id]=page;return true;
 }
 snapshot(){return {schemaVersion:1,carried:[...this.carried],bookmarks:{...this.bookmarks},fontSize:this.fontSize};}
}
